#!/usr/bin/env python3
"""Converts the SVG icons in design/icons into Android VectorDrawables (app/src/main/res/drawable).

Android cannot render raw .svg files at runtime, so the SVGs are the source of truth and this
script produces the XML the app actually uses. Supports <path> elements with d, fill,
fill-rule, stroke, stroke-width, stroke-linecap and stroke-linejoin, in a square viewBox.

Usage: python3 scripts/svg2vector.py
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "design" / "icons"
DST = ROOT / "app" / "src" / "main" / "res" / "drawable"
NS = "{http://www.w3.org/2000/svg}"


def color(value, default="#000000"):
    if value is None or value == "currentColor":
        value = default
    if value == "none":
        return None
    value = value.strip()
    if re.fullmatch(r"#[0-9a-fA-F]{3}", value):
        value = "#" + "".join(c * 2 for c in value[1:])
    if re.fullmatch(r"#[0-9a-fA-F]{6}", value):
        return "#FF" + value[1:].upper()
    if re.fullmatch(r"#[0-9a-fA-F]{8}", value):
        return value.upper()
    raise ValueError(f"unsupported colour: {value}")


def convert(svg_path: Path) -> str:
    root = ET.parse(svg_path).getroot()
    view_box = [float(x) for x in root.attrib["viewBox"].replace(",", " ").split()]
    width, height = view_box[2], view_box[3]
    size = int(root.attrib.get("width", str(int(width))).replace("px", ""))

    paths = []
    for el in root.iter(NS + "path"):
        d = re.sub(r"\s+", " ", el.attrib["d"].strip())
        attrs = [f'android:pathData="{d}"']
        fill = color(el.attrib.get("fill"))
        if fill:
            attrs.append(f'android:fillColor="{fill}"')
        stroke = color(el.attrib.get("stroke"), default="none")
        if stroke:
            attrs.append(f'android:strokeColor="{stroke}"')
            attrs.append(f'android:strokeWidth="{el.attrib.get("stroke-width", "1")}"')
            if "stroke-linecap" in el.attrib:
                attrs.append(f'android:strokeLineCap="{el.attrib["stroke-linecap"]}"')
            if "stroke-linejoin" in el.attrib:
                attrs.append(f'android:strokeLineJoin="{el.attrib["stroke-linejoin"]}"')
        if el.attrib.get("fill-rule") == "evenodd":
            attrs.append('android:fillType="evenOdd"')
        body = "\n        ".join(attrs)
        paths.append(f"    <path\n        {body} />")
    if not paths:
        raise ValueError(f"{svg_path.name}: no <path> elements found")

    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by scripts/svg2vector.py from design/icons/"
        f"{svg_path.name}. Edit the SVG, not this file. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size}dp"\n'
        f'    android:height="{size}dp"\n'
        f'    android:viewportWidth="{width:g}"\n'
        f'    android:viewportHeight="{height:g}">\n'
        + "\n".join(paths)
        + "\n</vector>\n"
    )


def main() -> int:
    DST.mkdir(parents=True, exist_ok=True)
    svgs = sorted(SRC.glob("*.svg"))
    if not svgs:
        print("No SVG files found in", SRC, file=sys.stderr)
        return 1
    for svg in svgs:
        out = DST / (svg.stem + ".xml")
        out.write_text(convert(svg), encoding="utf-8")
        print(f"{svg.name} -> {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
