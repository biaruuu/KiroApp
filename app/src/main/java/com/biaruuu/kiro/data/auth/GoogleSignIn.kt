package com.biaruuu.kiro.data.auth

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import kotlin.coroutines.resume
import kotlinx.coroutines.suspendCancellableCoroutine

/** "Continue with Google": Credential Manager picks the account, Firebase turns it into a session. */
object GoogleSignIn {

    /** Returns null on success, "" when the user backed out, or a message to show. */
    suspend fun signIn(activityContext: Context): String? {
        // Generated by the Google services plugin only when Google sign-in is enabled in Firebase.
        val id = activityContext.resources.getIdentifier("default_web_client_id", "string", activityContext.packageName)
        if (id == 0) return "Google sign-in isn't set up for this build."
        val clientId = activityContext.getString(id)

        val request = GetCredentialRequest.Builder()
            .addCredentialOption(
                GetGoogleIdOption.Builder()
                    .setFilterByAuthorizedAccounts(false)
                    .setServerClientId(clientId)
                    .build(),
            )
            .build()

        val token = try {
            val result = CredentialManager.create(activityContext).getCredential(activityContext, request)
            val c = result.credential
            if (c is CustomCredential && c.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                GoogleIdTokenCredential.createFrom(c.data).idToken
            } else {
                return "Google sign-in failed. Please try again."
            }
        } catch (e: GetCredentialCancellationException) {
            return ""
        } catch (e: NoCredentialException) {
            return "No Google account found on this device."
        } catch (e: GetCredentialException) {
            return "Google sign-in failed. Please try again."
        } catch (e: Exception) {
            return "Google sign-in failed. Please try again."
        }

        return suspendCancellableCoroutine { cont ->
            AuthRepository.signInWithGoogle(token) { err -> if (cont.isActive) cont.resume(err) }
        }
    }
}
